export function glyphCells(rows: readonly string[]) {
  const cells: [number, number][] = []
  rows.forEach((row, y) => [...row].forEach((c, x) => { if (c === '#') cells.push([x, y]) }))
  return { cells, width: rows[0].length, height: rows.length }
}

// Generador determinista para que cada página tenga siempre el mismo dibujo.
export function seeded(seed: string) {
  let h = 1779033703 ^ seed.length
  for (let i = 0; i < seed.length; i++) { h = Math.imul(h ^ seed.charCodeAt(i), 3432918353); h = (h << 13) | (h >>> 19) }
  let a = h >>> 0
  return () => {
    a = (a + 0x6d2b79f5) | 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}
